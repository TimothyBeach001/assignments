def make_album(artist, title):
	return f"Album: {title} by {artist}"

print(make_album("The Beatles", "Abbey Road"))
print(make_album("Pink Floyd", "The Dark Side of the Moon"))
print(make_album("Michael Jackson", "Thriller"))

